# markdown rendering
# --------------------------------------------------------------------------- #

def render_key_contract(prose: str, rows: list[list[str]], tail: str) -> str:
    parts = []
    if prose:
        parts.append(prose)
    if rows:
        table = ["| Keys | Effect |", "| --- | --- |"]
        for action, keys in rows:
            table.append(f"| `{action}` | {keys or '—'} |")
        parts.append("\n".join(table))
    if tail:
        parts.append(tail)
    return "\n\n".join(parts)


def bullet(text: str) -> str:
    """Prefix a `- ` unless the hand-written line already carries a marker."""
    return text if text.lstrip().startswith(("- ", "* ")) else "- " + text


def render_page(w: dict, prose: dict, godoc: dict, pkgs: dict) -> str:
    slug = w["slug"]
    g = godoc.get(slug, {})
    lines: list[str] = []

    # ---- front matter ----------------------------------------------------- #
    fm = {
        "title": w["name"],
        "weight": w["weight"],
        "description": w["summary"],
        "widgetName": w["name"],
        "widgetPackage": w["package"],
        "widgetConstructor": w["constructor"],
        "capture": slug,
    }
    lines.append("---")
    for key, value in fm.items():
        lines.append(f'{key}: {json.dumps(value)}')
    lines.append("---")
    lines.append("")

    # ---- 1. what it is --------------------------------------------------- #
    lines.append(w["summary"])
    lines.append("")
    lines.append(
        f"Package `{w['package']}`. API reference: "
        f"[pkg.go.dev/{w['package']}](https://pkg.go.dev/github.com/serkanalgur/termmosaic/{w['package']})."
    )
    lines.append("")
    if g.get("intro"):
        lines.append(render_intro(g["intro"]))
        lines.append("")

    # ---- 2. captures ----------------------------------------------------- #
    lines.append("## Rendered output")
    lines.append("")
    lines.append("{{< widget-capture " + slug + " >}}")
    lines.append("")
    # The capture tool's own note, unless a hand-written one overrides it. The
    # override exists because the manifest and the godoc disagreed once: the
    # KeyHint note said the bar drops its lowest-priority bindings, the godoc and
    # the 40-column capture both say it truncates with a marker. Where they
    # disagree the capture is the evidence and the godoc is right.
    note = prose.get("note") or w.get("note")
    if note:
        lines.append(f"> **About this capture.** {note}")
        lines.append("")

    # ---- 3. package context ---------------------------------------------- #
    pkg = pkgs.get(w["package"], {})
    if pkg.get("intro"):
        lines.append("## Package context")
        lines.append("")
        lines.append(render_intro(pkg["intro"]))
        lines.append("")
    if pkg.get("extra"):
        lines.append(render_intro(pkg["extra"]))
        lines.append("")

    # ---- 4. constructing it ---------------------------------------------- #
    lines.append("## Constructing it")
    lines.append("")
    lines.append(f"```go\n{w['constructor']}\n```")
    lines.append("")
    if prose.get("constructing"):
        lines.append(prose["constructing"])
        lines.append("")
    for field in prose.get("fields", []):
        lines.append(f"- `{field['name']}` — {field['doc']}")
    if prose.get("fields"):
        lines.append("")

    # ---- 5. key contract ------------------------------------------------- #
    kc = g.get("keyContract")
    if kc and kc["rows"]:
        lines.append("## Key contract")
        lines.append("")
        lines.append(render_key_contract(kc["before"], kc["rows"], kc["after"]))
        lines.append("")
        if prose.get("keyNotes"):
            lines.append(prose["keyNotes"])
            lines.append("")

    # ---- 6. accessibility ------------------------------------------------ #
    a11y = g.get("sections", {}).get("Accessibility")
    if a11y:
        lines.append("## Accessibility")
        lines.append("")
        lines.append(render_intro(a11y))
        lines.append("")
    if prose.get("accessibility"):
        lines.append("## More on accessibility")
        lines.append("")
        lines.append(prose["accessibility"])
        lines.append("")

    # ---- 7. cost --------------------------------------------------------- #
    cost = g.get("sections", {}).get("Cost")
    if cost:
        lines.append("## What it costs")
        lines.append("")
        lines.append(render_intro(cost))
        lines.append("")

    # ---- 8. when not to use it (hand-written) ---------------------------- #
    lines.append("## When not to use it")
    lines.append("")
    for para in prose["whenNotToUse"]:
        lines.append(para)
        lines.append("")
    if prose.get("instead"):
        lines.append("**Instead:** " + prose["instead"])
        lines.append("")

    # ---- 9. related ------------------------------------------------------ #
    lines.append("## Related")
    lines.append("")
    related = [bullet(r) for r in prose.get("related", [])]
    related.append("- [TermMosaic limitations that apply to every widget](/limitations/)")
    related.append(
        f"- Source: [`{w['package']}` on GitHub]"
        f"(https://github.com/serkanalgur/termmosaic/tree/main/{w['package']})"
    )
    lines.append("\n".join(related))

    return "\n".join(lines).rstrip() + "\n"


def render_index(manifest: dict, prose: dict) -> str:
    groups: dict[str, list[dict]] = {}
    for w in manifest["widgets"]:
        groups.setdefault(w["package"], []).append(w)

    lines = [
        "---",
        'title: "Widgets"',
        "weight: 40",
        'description: "All 22 widgets, with a captured frame at three widths for each."',
        "---",
        "",
        f"TermMosaic ships **{manifest['widgetCount']} widgets**. That number is the whole claim and it is "
        "counted, not estimated: it is every exported type with a `New…` constructor that satisfies "
        "`termmosaic.Widget`, and `buffer.Buffer` is deliberately not on the list because it is what widgets "
        "draw *into*, not a widget.",
        "",
        "`widgets/form/optionlist.go` is an unexported shared helper behind `Select`, `Tabs` and `KeyHint`; it is "
        "not a twenty-third widget.",
        "",
        "> There is no `Form` container widget. A `Form` type would have been a second way to do what "
        "[ADR 0004](/adr/0004-layout-engine/)'s constraint solver and the `layout` package already do, so it was "
        "not built. See [Forms](/guides/forms/) for how the form widgets compose.",
        "",
        "Every page below carries the widget's captured frame at 40, 80 and 120 columns. Read "
        "[what a capture can and cannot show](/limitations/#captures-are-cell-grids-not-terminal-screenshots) "
        "before you read one as a promise about your own terminal.",
        "",
    ]
    titles = {
        "widgets/block": "Core",
        "widgets/basic": "Core",
        "widgets/split": "Core",
        "widgets/form": "Forms",
        "widgets/data": "Data",
        "widgets/viz": "Visualization",
    }
    for pkg, entries in groups.items():
        lines.append(f"## {titles.get(pkg, pkg)} — `{pkg}`")
        lines.append("")
        lines.append("| Widget | Summary | MinSize |")
        lines.append("| --- | --- | --- |")
        for e in entries:
            ms = e.get("minSize")
            cell = f"{ms['w']}×{ms['h']}" if ms else "—"
            lines.append(
                f"| [`{e['name']}`](/widgets/{e['slug']}/) | {e['summary']} | {cell} |"
            )
        lines.append("")
    return "\n".join(lines)


