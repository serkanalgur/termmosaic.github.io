def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--framework", default=None, help="path to the termmosaic checkout")
    ap.add_argument("--refresh-godoc", action="store_true")
    ap.add_argument("--check", action="store_true", help="fail if output would change")
    args = ap.parse_args()

    manifest = json.loads((REPO / "static/captures/manifest.json").read_text(encoding="utf-8"))
    prose_all = json.loads((REPO / "data/widget_prose.json").read_text(encoding="utf-8"))

    framework = Path(args.framework) if args.framework else None
    godoc_path = REPO / "data/godoc.json"

    if args.refresh_godoc:
        if framework is None:
            sys.exit("--refresh-godoc requires --framework")
        cache = refresh_godoc(framework)
        godoc_path.write_text(
            json.dumps(cache, indent=2, ensure_ascii=False, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        print(
            f"wrote {godoc_path.relative_to(REPO)} "
            f"({len(cache['widgets'])} widgets, {len(cache['packages'])} packages)"
        )
    else:
        if not godoc_path.exists():
            sys.exit("data/godoc.json missing; run with --refresh-godoc --framework <path>")
        cache = json.loads(godoc_path.read_text(encoding="utf-8"))

    godoc = cache["widgets"]
    pkgs = cache["packages"]

    slugs = [w["slug"] for w in manifest["widgets"]]
    if len(slugs) != manifest["widgetCount"]:
        sys.exit(f"manifest says {manifest['widgetCount']} widgets, lists {len(slugs)}")
    if len(set(slugs)) != len(slugs):
        sys.exit("duplicate slugs in manifest")
    missing = [s for s in slugs if s not in godoc]
    if missing:
        sys.exit(f"no godoc for: {', '.join(missing)}")
    missing_prose = [s for s in slugs if s not in prose_all]
    if missing_prose:
        sys.exit(f"no hand-written prose for: {', '.join(missing_prose)}")
    if "form" in prose_all:
        sys.exit("there is no Form widget; remove the entry")
    unknown = sorted(set(prose_all) - set(slugs) - {"_comment"})
    if unknown:
        sys.exit(f"prose for widgets not in the manifest: {', '.join(unknown)}")

    out_dir = REPO / "content/widgets"
    out_dir.mkdir(parents=True, exist_ok=True)

    for weight, w in enumerate(manifest["widgets"], start=1):
        enriched = dict(w, weight=weight)
        page = render_page(enriched, prose_all[w["slug"]], godoc, pkgs)
        (out_dir / f"{w['slug']}.md").write_text(page, encoding="utf-8")

    (out_dir / "_index.md").write_text(render_index(manifest, prose_all), encoding="utf-8")

    stale = sorted(set(p.stem for p in out_dir.glob("*.md")) - set(slugs) - {"_index"})
    if stale:
        sys.exit(f"pages in content/widgets/ with no manifest entry: {', '.join(stale)}")

    print(f"wrote {len(slugs)} widget pages + _index.md to {out_dir.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())