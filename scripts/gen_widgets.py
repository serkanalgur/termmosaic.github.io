#!/usr/bin/env python3
"""Generate the 22 widget pages from data the framework already produced.

Three inputs, three different provenances, and the script refuses to invent any
of them:

  static/captures/manifest.json  generated by cmd/capture in the framework repo.
                                 Names, packages, constructors, summaries, notes,
                                 MinSize, the three capture widths. Never edited.
  data/godoc.json                extracted from the framework's Go source by
                                 --refresh-godoc. Cached so the site repo can be
                                 rebuilt without a framework checkout.
  data/widget_prose.json         hand-written. "When NOT to use this" is the one
                                 section a capture cannot generate.

Output: content/widgets/<slug>.md, committed. Re-running is idempotent; a
non-empty diff means an input moved.

Usage:
  scripts/gen_widgets.py                          # rebuild from cached inputs
  scripts/gen_widgets.py --refresh-godoc          # re-extract from the framework
  scripts/gen_widgets.py --framework ../Projects/termmosaic --check
"""

