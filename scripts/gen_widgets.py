# Go doc headings that become their own widget-page section. Everything else in a
# type's doc comment becomes the intro prose. The order here is the order on the
# page; a heading not in this map is dropped, because an unmapped Go heading
# would silently become prose and read as a heading that is not there.
SECTION_ORDER = ["Key contract", "Accessibility", "Cost", "Colour is never the only signal"]


# --------------------------------------------------------------------------- #
# godoc extraction
# --------------------------------------------------------------------------- #

def strip_doc(lines: list[str]) -> list[str]:
    """Drop the `//` prefix and the single space Go convention adds after it."""
    out = []
    for line in lines:
        if line.startswith("// "):
            out.append(line[3:])
        elif line == "//":
            out.append("")
        elif line.startswith("//"):
            out.append(line[2:])
        else:
            out.append(line)
    return out


def type_doc(src: str, typename: str) -> list[str]:
    """Return the doc comment immediately preceding `type <typename> ...`."""
    lines = src.split("\n")
    idx = None
    for i, line in enumerate(lines):
        if re.match(rf"^type {re.escape(typename)}\b", line):
            idx = i
            break
    if idx is None:
        raise LookupError(f"no declaration for `type {typename}`")

    # The declaration may carry the name on its own line or share a line with
    # other members; walk back over the comment block either way.
    doc: list[str] = []
    i = idx - 1
    while i >= 0 and lines[i].startswith("//"):
        doc.append(lines[i])
        i -= 1
    return list(reversed(strip_doc(doc)))


def split_sections(lines: list[str]) -> tuple[str, dict[str, str]]:
    """Split a Go doc comment into (intro prose, {# Heading: body} sections)."""
    intro: list[str] = []
    sections: dict[str, list[str]] = {}
    current: str | None = None

    for line in lines:
        heading = re.match(r"^# (.+?)\s*$", line)
        if heading:
            current = heading.group(1)
            sections[current] = []
            continue
        if current is None:
            intro.append(line)
        else:
            sections[current].append(line)

    return "\n".join(intro).strip(), {k: "\n".join(v).strip() for k, v in sections.items()}


def package_doc(src: str, pkgname: str) -> list[str]:
    """Return the doc comment immediately preceding the `package` clause."""
    lines = src.split("\n")
    doc: list[str] = []
    seen = False
    for line in lines:
        if line.startswith(f"package {pkgname}"):
            break
        if line.startswith("//"):
            doc.append(line)
            seen = True
        elif line.strip() == "":
            if seen:
                break
        elif seen:
            break
    return strip_doc(doc)


def contract_table(body: str) -> tuple[str, list[tuple[str, str]], str]:
    """Split a `# Key contract` body into (prose before, rows, prose after).

    The binding rows are an indented block a human wrote as aligned columns:

        activate      KeyEnter, KeySpace
        focus         a left click inside Bounds, which also activates

    They are recognised by their leading tab, not by their alignment, so the
    prose around them — which carries the negative claims that make a contract
    worth reading ("KeyTab is NOT consumed") — is kept rather than swallowed.
    """
    prose: list[str] = []
    rows: list[tuple[str, str]] = []
    tail: list[str] = []
    in_rows = False

    for raw in body.split("\n"):
        if raw.startswith("\t"):
            parts = re.split(r"\s{2,}", raw.strip())
            if len(parts) >= 2:
                rows.append([parts[0].strip(), " ".join(parts[1:]).strip()])
                in_rows = True
                continue
            # A single column: the effect wrapped onto its own aligned line.
            if rows:
                rows[-1][1] = (rows[-1][1] + " " + raw.strip()).strip()
            else:
                rows.append([raw.strip(), ""])
            in_rows = True
            continue
        if raw.strip() == "":
            continue
        # Prose before the first row introduces it; prose after it qualifies it.
        (tail if in_rows else prose).append(raw.strip())

    return " ".join(prose), rows, " ".join(tail)


LIST_MARKER = re.compile(r"^\s*(?:[-*]|\d+\.)\s+(.*)$")


def render_intro(text: str) -> str:
    """Go doc prose -> markdown, block by block.

    Go doc comments use three shapes that markdown renders differently: prose
    paragraphs, literal blocks indented with a tab, and lists — bulleted or
    numbered — whose continuation lines are indented to align under the first
    item. Rewrapping prose and preserving indentation renders all three, so this
    walks lines and classifies each into one of the three rather than splitting
    on blank lines, which would fuse a three-item list into one paragraph.
    """
    blocks: list[tuple[str, list]] = []
    current: list | None = None

    def begin(kind: str):
        nonlocal current
        current = [kind, []]
        blocks.append(current)

    for raw in text.split("\n"):
        if raw.startswith("\t"):
            # Literal block. Continuation lines inside one are indented too.
            if current is None or current[0] != "pre":
                begin("pre")
            current[1].append(raw[1:])
            continue
        if not raw.strip():
            current = None
            continue
        marker = LIST_MARKER.match(raw)
        if marker:
            if current is None or current[0] != "list":
                begin("list")
            current[1].append([marker.group(1)])
            continue
        if current is not None and current[0] == "list":
            current[1][-1].append(raw.strip())
            continue
        if current is None or current[0] != "p":
            begin("p")
        current[1].append(raw.strip())

    out: list[str] = []
    for kind, body in blocks:
        if kind == "p":
            out.append(" ".join(body))
        elif kind == "list":
            out.append("\n".join("- " + " ".join(item) for item in body))
        else:
            out.append("\n".join(("    " + ln) if ln.strip() else "" for ln in body))
    return "\n\n".join(x for x in out if x.strip())


def refresh_godoc(framework: Path) -> dict:
    if not framework.is_dir():
        sys.exit(f"framework repo not found at {framework}")

    # Package narrative is identical for every widget in a package; extract once.
    packages: dict[str, dict] = {}
    for pkg, (base, extra) in PKG_SOURCE.items():
        src = (framework / pkg / f"{base}.go").read_text(encoding="utf-8")
        intro, sections = split_sections(package_doc(src, base))
        packages[pkg] = {"intro": intro, "extra": sections.get(extra) if extra else None}

    out: dict[str, dict] = {}
    for slug, (rel, typename) in WIDGET_SOURCE.items():
        src = (framework / rel).read_text(encoding="utf-8")
        intro, sections = split_sections(type_doc(src, typename))
        entry: dict = {"intro": intro, "sections": sections}
        if "Key contract" in sections:
            before, rows, after = contract_table(sections["Key contract"])
            entry["keyContract"] = {"before": before, "rows": rows, "after": after}
        out[slug] = entry
    return {"packages": packages, "widgets": out}


